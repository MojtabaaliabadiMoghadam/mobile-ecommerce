let seedPromise: Promise<void> | null = null;
export async function ensureSeeded() {
  if (seedPromise) return seedPromise;
  seedPromise = (async () => {
    try {
      if (!(await isSeeded())) {
        await runSeed();
        console.log("✅ Database seeded");
      } else if ((await db.select({ id: articles.id }).from(articles).limit(1)).length === 0) {
        // دیتابیس از قبل پر است ولی بخش مقالات خالی مانده → فقط مقالات دمو ساخته می‌شوند
        const r = await seedDemoArticles();
        if (r.added) console.log(`📝 ${r.added} demo article(s) seeded`);
      }
    } catch (e) {
      console.error("Seed failed", e);
      seedPromise = null;
    }
  })();
  return seedPromise;
}
